"""Makes src/css/fonts.css again with all the families that the report can use (latin subset, variable woff2, base64).

Usage: python -I tools/fetch_fonts.py <cache_dir>
Families (Google Fonts, SIL Open Font License 1.1): Inter, Playfair Display, Lora, Montserrat, Source Sans 3, Figtree.
"""
import base64, hashlib, os, re, sys, urllib.request

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = sys.argv[1]
os.makedirs(CACHE, exist_ok=True)
UA = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"}
FAMILIES = [
    "Inter:wght@400..800",
    "Cormorant+Garamond:ital,wght@0,500;0,600;0,700;1,500;1,600",
    "Literata:ital,wght@0,400..700;1,400..700",
    "Montserrat:wght@400..800",
    "Open+Sans:wght@400..800",
    "Figtree:wght@400..800",
]


def header(note):
    h = open(os.path.join(ROOT, 'tools', 'source-header.txt'), encoding='utf-8').read().strip()
    lines = (h + '\n\n' + note).split('\n')
    return '/*\n' + '\n'.join((' * ' + l) if l else ' *' for l in lines) + '\n */'


def fetch(url, name):
    path = os.path.join(CACHE, name)
    if os.path.exists(path):
        return open(path, "rb").read()
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        data = r.read()
    open(path, "wb").write(data)
    return data


def main():
    out = [header("The fonts embedded below (Latin subsets, as served by Google Fonts) are licensed under the SIL Open Font License 1.1;\nsee LICENSES/ and NOTICE. Generated by tools/fetch_fonts.py.")]
    total = 0
    for fam in FAMILIES:
        css = fetch("https://fonts.googleapis.com/css2?family=" + fam + "&display=swap", "css_" + re.sub(r"\W", "_", fam) + ".css").decode("utf-8")
        for m in re.finditer(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S):
            subset, block = m.group(1), m.group(2)
            if subset != "latin":
                continue
            url = re.search(r"url\((https://[^)]+)\)\s*format\(['\"]woff2['\"]\)", block).group(1)
            name = re.search(r"font-family:\s*'([^']+)'", block).group(1)
            style = re.search(r"font-style:\s*(\w+)", block).group(1)
            data = fetch(url, "f_" + hashlib.sha1(url.encode()).hexdigest()[:20] + ".woff2")
            total += len(data)
            out.append(f"/* {name} {style} latin */\n" + block.replace(url, "data:font/woff2;base64," + base64.b64encode(data).decode()))
            print(f"{name} {style}: {len(data) // 1024} KB")
    css = "\n".join(out) + "\n"
    open(os.path.join(ROOT, "src", "css", "fonts.css"), "w", encoding="utf-8", newline="\n").write(css)
    print(f"fonts.css: {len(css) // 1024} KB (woff2 {total // 1024} KB)")


if __name__ == "__main__":
    main()
