"""Makes src/js/assets.js (base maps of the report). tools/fetch_fonts.py makes the fonts, and
tools/build_profile_assets.py makes the logos of the example agencies.

Usage: python -I tools/fetch_assets.py <cache_dir>
- The tiles of Base IGN (WMTS GoogleMapsCompatible, © IGN España, CC BY 4.0) are downloaded one time and embedded
  in base64. (OpenStreetMap tiles are not used: their server does not permit automatic downloads.)
"""
import base64, json, math, os, re, sys, time, urllib.request

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = sys.argv[1]
os.makedirs(CACHE, exist_ok=True)
UA_APP = {"User-Agent": "Valesta-build/1.0 (offline report generator)"}
UA_BROWSER = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36"}

# The demo valuation (src/js/data.js): the subject, then the comparables T1-T7, R1 and R2.
SUBJECT = (41.2831, 1.9814)
POINTS = [SUBJECT, (41.2819, 1.9793), (41.2804, 1.9759), (41.2836, 1.9802), (41.2884, 1.9839),
          (41.2879, 1.9871), (41.2699, 1.9841), (41.2673, 1.9724), (41.2791, 1.9723), (41.2829, 1.9792)]



def header(note):
    h = open(os.path.join(ROOT, 'tools', 'source-header.txt'), encoding='utf-8').read().strip()
    lines = (h + '\n\n' + note).split('\n')
    return '/*\n' + '\n'.join((' * ' + l) if l else ' *' for l in lines) + '\n */'


def world_px(lat, lon, z):
    n = 256 * 2 ** z
    x = (lon + 180.0) / 360.0 * n
    r = math.radians(lat)
    y = (1 - math.log(math.tan(r) + 1 / math.cos(r)) / math.pi) / 2 * n
    return x, y


def fetch(url, headers, cache_name):
    p = os.path.join(CACHE, cache_name)
    if os.path.exists(p) and os.path.getsize(p) > 0:
        return open(p, "rb").read()
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=40) as r:
        data = r.read()
    open(p, "wb").write(data)
    time.sleep(0.35)
    return data


def build_map(name, z, x0, y0, w, h):
    tiles = []
    for ty in range(int(y0 // 256), int((y0 + h) // 256) + 1):
        for tx in range(int(x0 // 256), int((x0 + w) // 256) + 1):
            url = ("https://www.ign.es/wmts/ign-base?SERVICE=WMTS&REQUEST=GetTile&VERSION=1.0.0&LAYER=IGNBaseTodo&STYLE=default"
                   f"&TILEMATRIXSET=GoogleMapsCompatible&TILEMATRIX={z}&TILEROW={ty}&TILECOL={tx}&FORMAT=image/jpeg")
            data = fetch(url, UA_APP, f"ign_{z}_{tx}_{ty}.jpg")
            assert data[:3] == b"\xff\xd8\xff" and len(data) > 2000, f"tile {z}/{tx}/{ty} is not a valid JPEG map tile"
            tiles.append({"x": tx * 256 - x0, "y": ty * 256 - y0, "d": "data:image/jpeg;base64," + base64.b64encode(data).decode()})
    print(f"map {name}: z{z} {len(tiles)} tiles, viewport {w:.0f}x{h:.0f}")
    return {"z": z, "x0": x0, "y0": y0, "w": w, "h": h, "tiles": tiles,
            "attribution": "© Instituto Geográfico Nacional (IGN) · CC BY 4.0"}


def maps():
    # micro: z16 centred on the subject
    z = 16
    cx, cy = world_px(*SUBJECT, z)
    W, H = 840, 560
    micro = build_map("micro", z, cx - W / 2, cy - H / 2, W, H)
    # overview: z15 bbox of subject + comparables with padding, portrait-ish
    z = 15
    pts = [world_px(lat, lon, z) for lat, lon in POINTS]
    minx, maxx = min(p[0] for p in pts), max(p[0] for p in pts)
    miny, maxy = min(p[1] for p in pts), max(p[1] for p in pts)
    pad = 70
    w, h = (maxx - minx) + 2 * pad, (maxy - miny) + 2 * pad
    target = 0.82  # w/h
    if w / h < target:
        extra = h * target - w
        minx -= extra / 2
        w = h * target
    overview = build_map("overview", z, minx - pad, miny - pad, w, h)
    return {"micro": micro, "overview": overview}


def main():
    m = maps()
    js = (header("Generic report assets, generated by tools/fetch_assets.py.\nThe base map tiles embedded below are © Instituto Geográfico Nacional de España (IGN),\nlicensed under CC BY 4.0 (LICENSES/CC-BY-4.0.txt).") + "\n"
          "(function (root) {\n  const ASSETS = " + json.dumps({"maps": m}, ensure_ascii=False) +
          ";\n  if (typeof module === 'object' && module.exports) module.exports = ASSETS; else root.ASSETS = ASSETS;\n"
          "})(typeof self !== 'undefined' ? self : this);\n")
    open(os.path.join(ROOT, "src", "js", "assets.js"), "w", encoding="utf-8").write(js)
    print("assets.js", len(js) // 1024, "KB")


if __name__ == "__main__":
    main()
