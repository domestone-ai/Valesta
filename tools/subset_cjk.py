"""Regenerates src/css/fonts-cjk.css: Noto Sans SC (SIL Open Font License 1.1) cut to the Chinese characters the
report can print, in weights 400 and 700, as WOFF2 in base64. Chinese PDFs then look the same on every computer.

Usage: <python with fonttools and brotli> -I tools/subset_cjk.py <NotoSansSC[wght].ttf>
The variable font and its OFL.txt come from https://github.com/google/fonts/tree/main/ofl/notosanssc. The licence
names the Reserved Font Name 'Source', which the cut font does not use. Run it again when the Chinese texts change
(the test "the Chinese report embeds Noto Sans SC…" says so)."""
import base64
import io
import os
import re
import subprocess
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CJK = re.compile(r'[\u3000-\u303F\u4E00-\u9FFF\uFF00-\uFFEF]')
# Punctuation and full-width forms a Chinese text may use besides the ones in the sources.
EXTRA = '，。、；：？！“”‘’（）《》【】「」『』…—·～￥％＋－×÷＝０１２３４５６７８９'
# Strings the report builds at run time: dates and region names from Intl, in Chinese.
NODE_STRINGS = r"""
const out = [];
const df = new Intl.DateTimeFormat('zh-CN', { year: 'numeric', month: 'long', day: 'numeric' });
for (let m = 0; m < 12; m++) out.push(df.format(new Date(Date.UTC(2026, m, 15))));
const dn = new Intl.DisplayNames(['zh'], { type: 'region' });
const T = require(process.argv[1] + '/src/js/taxonomy.js');
for (const c of T.COUNTRIES) out.push(dn.of(c.code));
for (const c of ['IT', 'ES', 'FR', 'DE', 'PT', 'NL', 'BE', 'LU', 'AT', 'CH', 'GB', 'IE', 'PL', 'CZ', 'SK', 'HU', 'RO', 'HR', 'SI', 'DK', 'SE', 'NO', 'FI', 'GR', 'MT', 'CY', 'US', 'CN']) out.push(dn.of(c));
process.stdout.write(out.join('\n'));
"""


def characters():
    text = ''
    for rel in ['src/js/lang/report.zh.js', 'src/js/numwords.js', 'src/js/i18n.js']:
        text += open(os.path.join(ROOT, rel), encoding='utf-8').read()
    text += subprocess.run(['node', '-e', NODE_STRINGS, ROOT], capture_output=True, check=True, text=True, encoding='utf-8').stdout
    return sorted({ch for ch in text + EXTRA if CJK.match(ch)})


def ranges(cps):
    out, start, prev = [], None, None
    for cp in cps:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            out.append((start, prev))
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return ', '.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)


def cut(src, weight, cps):
    font = instancer.instantiateVariableFont(TTFont(src), {'wght': weight}, updateFontNames=True)
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=cps)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf)
    return buf.getvalue()


def header(note):
    h = open(os.path.join(ROOT, 'tools', 'source-header.txt'), encoding='utf-8').read().strip()
    lines = (h + '\n\n' + note).split('\n')
    return '/*\n' + '\n'.join((' * ' + l) if l else ' *' for l in lines) + '\n */'


def main():
    src = sys.argv[1]
    chars = characters()
    cps = [ord(c) for c in chars]
    urange = ranges(cps)
    out = [header('The font embedded below is Noto Sans SC, Copyright 2014-2021 Adobe (http://www.adobe.com/), with Reserved Font\n'
                  'Name \'Source\', licensed under the SIL Open Font License 1.1 (LICENSES/OFL-1.1-NotoSansSC.txt). It is cut to\n'
                  f'the {len(cps)} Chinese characters the report can print. Generated by tools/subset_cjk.py.')]
    sizes = []
    for weight in (400, 700):
        data = cut(src, weight, cps)
        sizes.append(len(data))
        out.append("@font-face { font-family: 'Noto Sans SC'; font-style: normal; font-weight: %d; font-display: swap;\n"
                   "  src: url(data:font/woff2;base64,%s) format('woff2');\n  unicode-range: %s; }" % (weight, base64.b64encode(data).decode('ascii'), urange))
    with open(os.path.join(ROOT, 'src', 'css', 'fonts-cjk.css'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'fonts-cjk.css: {len(cps)} characters, WOFF2 {sizes[0] // 1024} KB + {sizes[1] // 1024} KB')


if __name__ == '__main__':
    main()
