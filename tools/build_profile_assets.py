"""Generate src/js/profiles_assets.js: logos of the fictitious example agencies (sanitised SVG, base64).

Usage: python -I tools/build_profile_assets.py
Sources in tools/brand-src/: <name>-light.svg and <name>-dark.svg, created for this project. The example agencies
are fictitious and do not represent real companies.
"""
import base64
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "brand-src")
OUT = os.path.join(ROOT, "src", "js", "profiles_assets.js")
LOGOS = {"casaaurora": "casa-aurora", "mirador": "mirador", "nordichomes": "nordic-homes"}


def header(note):
    h = open(os.path.join(ROOT, "tools", "source-header.txt"), encoding="utf-8").read().strip()
    lines = (h + "\n\n" + note).split("\n")
    return "/*\n" + "\n".join((" * " + l) if l else " *" for l in lines) + "\n */"


def clean(svg):
    """Static SVG only: no scripts, events, external references, styles or classes."""
    s = re.sub(r"<\?xml[^>]*\?>|<!--.*?-->|<title>.*?</title>", "", svg, flags=re.S)
    s = re.sub(r"<(script|foreignObject|style)\b.*?</\1>", "", s, flags=re.S | re.I)
    s = re.sub(r"\s(on\w+|xlink:href|href)=\"[^\"]*\"", "", s, flags=re.I)
    s = re.sub(r"\s+", " ", s).strip()
    if 'xmlns="http://www.w3.org/2000/svg"' not in s:
        s = s.replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ', 1)
    for bad in ("<script", "javascript:", "<image", "<use", "@import"):
        assert bad not in s.lower(), bad
    return s


def data_url(svg):
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode("utf-8")).decode("ascii")


def main():
    read = lambda f: open(os.path.join(SRC, f), encoding="utf-8").read()
    assets = {key: {"light": clean(read(f"{name}-light.svg")), "dark": clean(read(f"{name}-dark.svg"))} for key, name in LOGOS.items()}
    lines = [header("Logos of the fictitious example agencies, generated by tools/build_profile_assets.py."),
             "(function (root) {", "  const PROFILE_ASSETS = {"]
    for key, v in assets.items():
        lines.append(f"    {key}: {{ light: '{data_url(v['light'])}', dark: '{data_url(v['dark'])}' }},")
    lines += ["  };", "  if (typeof module === 'object' && module.exports) module.exports = PROFILE_ASSETS; else root.PROFILE_ASSETS = PROFILE_ASSETS;",
              "})(typeof self !== 'undefined' ? self : this);", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("profiles_assets.js", os.path.getsize(OUT) // 1024, "KB")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
